/* Builds Game Academy's original artwork into assets/art/*.svg
   and the layered home-page hero into js/hero-scene.js.
   Run: node tools/build-art.mjs */
import { writeFileSync, mkdirSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import * as W from "./art/scenes-world.mjs";
import * as U from "./art/scenes-ui.mjs";
import * as I from "./art/scenes-info.mjs";
import * as C from "./art/scenes-chars.mjs";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const out = join(root, "public", "assets", "art");
mkdirSync(out, { recursive: true });

const pieces = {
  "hero-summit": () => W.heroSummit(),
  "level-map": W.levelMap,
  "world-map": W.worldMap,
  "pixel-biomes": W.pixelBiomes,
  "iso-dungeon": W.isoDungeon,
  "lowpoly-forest": W.lowpolyForest,
  "ruined-city": W.ruinedCity,
  "hud": U.hud,
  "hud-before-after": U.hudBeforeAfter,
  "battle-ui": U.battleUI,
  "item-icons": U.itemIcons,
  "board-iso": U.boardIso,
  "pitch-board": U.pitchBoard,
  "seven-details": I.sevenDetails,
  "gdd-flow": I.gddFlow,
  "platformer-roadmap": I.platformerRoadmap,
  "env-elements": I.envElements,
  "progression": I.progression,
  "vector-layers": I.vectorLayers,
  "modular-kit": I.modularKit,
  "toolkit": I.toolkit,
  "three-traits": I.threeTraits,
  "cast-lineup": C.castLineup,
  ...Object.fromEntries(C.CAST.map(c => ["cast-" + c.id, () => C.castCard(c)]))
};

let total = 0;
for (const [name, fn] of Object.entries(pieces)) {
  const s = fn();
  writeFileSync(join(out, name + ".svg"), s);
  total += s.length;
  console.log(name.padEnd(20), (s.length / 1024).toFixed(1) + " KB");
}
const hero = W.heroSummit({ layered: true });
writeFileSync(join(root, "public", "js", "hero-scene.js"), `/* Generated by tools/build-art.mjs — layered home hero. */\nwindow.GA_HERO = ${JSON.stringify(hero)};\n`);
console.log("hero-scene.js".padEnd(20), (hero.length / 1024).toFixed(1) + " KB");
console.log("total", (total / 1024).toFixed(0) + " KB");
